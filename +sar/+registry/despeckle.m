function reg = despeckle(includeFailed)
% SAR.REGISTRY.DESPECKLE  Registry of despeckling methods
%   Returns a struct array of available filtering algorithms, their function
%   handles, parameter definitions, domain constraints, and input requirements.
%   If includeFailed is false (default), methods that failed validation are excluded.

if nargin < 1, includeFailed = false; end

allMethods = [
    struct(...
        'id', 'none', ...
        'name', 'None (Raw Amplitude)', ...
        'category', 'baseline', ...
        'status', 'ACTIVE', ...
        'inputType', 'any', ...
        'func', @(x, varargin) x, ...
        'params', struct(), ...
        'validationMetrics', struct(), ...
        'domainNote', 'Raw input without filtering.' ...
    ), ...
    struct(...
        'id', 'lee', ...
        'name', 'Lee Filter (Classical)', ...
        'category', 'classical', ...
        'status', 'ACTIVE', ...
        'inputType', 'amplitude', ...
        'func', @despeckle_filters, ...
        'params', struct('win', 7, 'L', 1), ...
        'validationMetrics', struct(), ...
        'domainNote', 'Classical adaptive filter. Yields ~0% intensity bias on fully developed speckle. Gives no downstream classification gain beyond augmentation.' ...
    ), ...
    struct(...
        'id', 'frost', ...
        'name', 'Frost Filter (Classical)', ...
        'category', 'classical', ...
        'status', 'ACTIVE', ...
        'inputType', 'amplitude', ...
        'func', @despeckle_filters, ...
        'params', struct('win', 7, 'L', 1), ...
        'validationMetrics', struct(), ...
        'domainNote', 'Exponentially damped adaptive filter (damping K=1). Gives no downstream classification gain beyond augmentation.' ...
    ), ...
    struct(...
        'id', 'gammamap', ...
        'name', 'Gamma-MAP Filter (Classical)', ...
        'category', 'classical', ...
        'status', 'ACTIVE', ...
        'inputType', 'amplitude', ...
        'func', @despeckle_filters, ...
        'params', struct('win', 7, 'L', 1), ...
        'validationMetrics', struct(), ...
        'domainNote', 'Maximum A Posteriori filter under Gamma speckle assumption. Possesses an intrinsic -3.8% intensity bias.' ...
    ), ...
    struct(...
        'id', 'merlin_mstar', ...
        'name', 'MERLIN (MSTAR-trained)', ...
        'category', 'deep', ...
        'status', 'ACTIVE', ...
        'inputType', 'complex', ...
        'func', @p3b_denoise, ...
        'params', struct('model', 'models/p3b_merlin.mat', 'scale', single(1)), ...
        'validationMetrics', struct(), ...
        'domainNote', 'Self-supervised complex despeckling network. REQUIRES COMPLEX single-look SAR input. Validated strictly on MSTAR chips (gain at <=10% labels; no gain at >=20%). distorts point targets (MSTAR net overshoots 1.54, Gotcha net undershoots 0.39).' ...
    ), ...
    struct(...
        'id', 'merlin_gotcha', ...
        'name', 'MERLIN (Gotcha-trained) [FAILED VALIDATION]', ...
        'category', 'deep', ...
        'status', 'FAILED_VALIDATION', ...
        'inputType', 'complex', ...
        'func', @p3b_denoise, ...
        'params', struct('model', 'models/p3b_merlin_gotcha.mat', 'scale', single(1)), ...
        'validationMetrics', struct('peakRatio', 0.39, 'widthX', 1.39, 'widthY', 1.45), ...
        'domainNote', 'FAILED VALIDATION on point targets (peak ratio 0.39, widths 1.39 and 1.45). Severely distorts point targets (undershoots 0.39). Not offered as an operational despeckling method.' ...
    )
];

if includeFailed
    reg = allMethods;
else
    reg = allMethods(strcmp({allMethods.status}, 'ACTIVE'));
end
end
